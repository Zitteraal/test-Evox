import html
import logging

from config import settings
from core import security
from core.tool_result import ToolResult

log = logging.getLogger("evox.projects")


class ProjectGenerator:
    @staticmethod
    def create_web_project(project_name: str) -> ToolResult:
        try:
            name = security.validate_project_name(project_name)
        except ValueError as exc:
            return ToolResult.failure(str(exc))

        root = settings.PROJECTS_DIR
        project_path = root / name

        # Niemals bestehende Projekte überschreiben
        if project_path.exists():
            return ToolResult.failure(
                f"A project or folder named '{name}' already exists at {project_path}. "
                "Choose a different name, or change the existing project with write_code_file."
            )

        title = html.escape(name)
        html_content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{title}</title>
    <link rel="stylesheet" href="style.css">
</head>
<body>
    <h1>Welcome to {title}</h1>
    <p>This project was generated by EVOX.</p>
    <script src="script.js"></script>
</body>
</html>"""
        css_content = (
            "body { font-family: 'Segoe UI', sans-serif; background: #0B1011; "
            "color: #E5EBE5; text-align: center; padding: 50px; }"
        )
        js_content = "console.log('EVOX Project Loaded');"

        files = {"index.html": html_content, "style.css": css_content, "script.js": js_content}
        try:
            project_path.mkdir(parents=True, exist_ok=False)
            for filename, content in files.items():
                (project_path / filename).write_text(content, encoding="utf-8")
        except OSError as exc:
            return ToolResult.failure(f"The project could not be created at {project_path}: {exc}")

        missing = [f for f in files if not (project_path / f).is_file() or (project_path / f).stat().st_size == 0]
        if missing:
            return ToolResult.failure(f"The project folder was created, but these files are missing or empty: {', '.join(missing)}")
        log.info("Web project created: %s", project_path)

        note = ""
        try:
            from computer_control import app_launcher

            vs = app_launcher.open_in_vscode(project_path, reuse_window=False)
            note = " Opened in VS Code." if vs.ok else f" (VS Code could not be opened: {vs.message})"
        except Exception as exc:  # noqa: BLE001
            note = f" (VS Code could not be opened: {exc})"

        return ToolResult.success(
            f"Created web project at {project_path} with index.html, style.css and script.js "
            f"(files checked).{note}",
            verified=True,
            path=str(project_path),
        )
